// Extracted mock reply generator so it can be tested independently
function generateMockReply(message, history){
  const m = (message||'').toString().trim();
  const low = m.toLowerCase();
  try{ console.log('[DEV_STUB] incoming message:', m); }catch(e){}

  if (!m) return 'Пустой запрос — пожалуйста, опишите вашу проблему или задайте вопрос коротко.';

  if (/^\s*привет|^\s*здравствуй|^\s*добрый/.test(low)){
    return 'Привет! Чем могу помочь? Опишите задачу (что хотите добиться, ОС, версии, ожидаемый результат).';
  }

  if (/исправь\s*(сам|себя)|исправь\s*ошибк/i.test(low)){
    return 'Могу помочь с отладкой и правками: пришлите точный текст ошибки или логи, укажите шаги для воспроизведения — я подготовлю пошаговый план и патчи при необходимости.';
  }

  if (/сделай\s*все\s*сам/i.test(low) || /сделай\s*всё\s*сам/i.test(low)){
    return 'Я могу автоматизировать большинство задач (сборка патчей, команды, конфигурация), но для доступа к вашему окружению мне нужны логи/команды и разрешение на запускаемые скрипты. Пришлите цель — я сгенерирую последовательность действий.';
  }

  if (/что\s*ты\s*умеешь\??|навыки|возможности/i.test(low)){
    return `Кратко — что я могу (DEV_STUB):\n- Проанализировать конфигурации и логи\n- Сгенерировать команды для установки и отладки\n- Подготовить патчи/изменения кода и инструкции\n- Подсказать по деплойменту и зависимостям\n- Привести примеры кода на популярных языках (Python, JS)\nПришлите задачу — дам конкретный план.`;
  }

  if (/напиши\s*полный\s*список|полный\s*список/i.test(low)){
    return `Подробный список возможностей:\n1) Анализ логов и предложений по исправлению\n2) Генерация/проверка конфигураций (Docker, npm, systemd)\n3) Создание/редактирование кода (JS/TS, Python, shell) и готовых патчей\n4) Настройка локальной среды и CI\n5) Руководства по сборке моделей (llama.cpp, whisper и т.д.)\n6) TTS/ASR/TTS-интеграция и тестовые сценарии\n7) Помощь с e2e тестами и playwright\n8) Рекомендации по безопасности и зависимостям\n\nСкажите, какой пункт интересует — подготовлю детальный план.`;
  }

  if (/\bязык\s*пайто?n?\b/i.test(low) || /^python$/i.test(low)){
    return 'Отлично, выбрали Python. Уточните цель: скрипт, веб-приложение, модель или утилита — подготовлю пример и зависимости.';
  }

  if (/пример|код|sample|demo|пример кода/i.test(m)){
    return `Пример (JavaScript):\n\nconsole.log('Hello, world');\n\nЕсли нужен Python — напишите цель (скрипт/веб/ML) и я дам пример.`;
  }

  if (/почему|как|что|когда|зачем|где|ошибка|exception|crash/i.test(low)){
    return `Краткий ответ: чаще всего причина в конфигурации или несовместимых версиях.\nЧто проверить (быстро):\n1) Содержимое последних логов (ошибки)\n2) Версии ключевых зависимостей\n3) Условия запуска (права, пути, переменные окружения)\n\nПришлите логи или точную команду — подготовлю конкретные команды для исправления.`;
  }

  if (history && history.length){
    const lastUser = history[history.length-1].user || '';
    return `Продолжаем: ${m}\n\nРанее: "${lastUser}". Предлагаю начать с\n1) сбора логов\n2) воспроизведения ошибки в простом сценарии\n3) подготовка патча по результатам.`;
  }

  return `Понял: ${m}\n\nЧтобы я помог максимально эффективно, укажите: ОС, версии (node/python), точную ошибку и шаги воспроизведения. Я сгенерирую команды и патч.`;
}

module.exports = { generateMockReply };
